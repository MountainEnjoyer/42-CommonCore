int	ft_atoi(const char *s)
{
	int	res;
	int	signe;
	int	i;

	signe = 1;
	if (s[0] == '-')
		signe = -1;
	i = 1;
	while (s[i])
	{
		res = res + (s[i] - '0');
		i++;
		res *= 10;
	}
	return (signe * res);
}
